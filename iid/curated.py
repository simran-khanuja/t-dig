"""Generate the curated i.i.d. image sets that axis elicitation reads.

Every prompt of a clustered pool gets K images (default 4) from each of the four T2I models,
generated by the native Diffusers pipelines of `baselines/` (method `iid`) from the unchanged
prompt. Layout of a run directory, read by `elicitation prepare` and `tdig.iid_vqa index`:

    plan.json, plan-hash.json      prompt hash, per-T2I-model configs and asset-lock hashes
    input.json, prompts.json       the clustered pool and its rows (id, prompt, cluster_id, split)
    <T2I model>/assets.lock.json   the T2I model's weight lock
    <T2I model>/shard-NN/manifest.json, summary.json, status.json
    <T2I model>/shard-NN/images/<prompt id>/<NNNN>/{image.png,receipt.json}
    <T2I model>/summary.json       all eight shards, written by `aggregate`

Rows are split into eight shards by sorted id (`rows[shard::8]`). Image `i` of a prompt uses the
seed `seed_for(prompt id, seed, i)`, so an image depends on neither its shard, its GPU nor resume
boundaries. Each image is committed atomically with a receipt; a rerun verifies committed images
and generates only the missing ones.
"""

import argparse
import json
import os
from pathlib import Path
import time
import uuid

from baselines.assets import expand_path, file_hash, seed_for, verify_assets
from baselines.config import T2I_MODELS, t2i_model_defaults, validate
from baselines.runner import environment, write_slot
from hpdv2.storage import atomic_json, digest, read_json, run_lock, sync_directory
from .runner import load_pool, verify_png

ROOT = Path(__file__).resolve().parents[1]
SHARDS = 8


def runtime():
    value = environment()
    value.pop('cuda_visible_devices', None)
    return value


def clean_rows(rows):
    # Screening axes of the curation must not reach the elicitor.
    return [
        {key: row[key] for key in ('id', 'prompt', 'cluster_id', 'split') if key in row}
        for row in sorted(rows, key=lambda r: r['id'])
    ]


def shard_rows(rows, shard):
    if type(shard) is not int or not 0 <= shard < SHARDS:
        raise ValueError('Invalid shard')
    return sorted(rows, key=lambda r: r['id'])[shard::SHARDS]


def manifest_for(plan, rows, t2i_model, shard):
    selected = shard_rows(rows, shard)
    return selected, dict(
        schema_version=1,
        kind='curated_iid_shard',
        plan_hash=digest(plan),
        config=plan['configs'][t2i_model],
        rows_sha256=digest(selected),
        shard=shard,
        workers=SHARDS,
        upstream_complete=plan['upstream_complete'],
        environment=plan['environment'],
        assets_sha256=plan['asset_hashes'][t2i_model],
    )


def prepare(input_path, out, k=4, seed=42, allow_partial=False, execute=False):
    """Freeze the prompts, configs and asset locks of a new run; write every shard manifest."""
    out = Path(out).resolve()
    if out.exists():
        raise ValueError('Use a new run directory; resume a prepared run with `run`')
    data, rows = load_pool(input_path, allow_partial)
    rows = clean_rows(rows)
    configs, locks = {}, {}
    for t2i_model in sorted(T2I_MODELS):
        cfg = t2i_model_defaults('iid', t2i_model)
        cfg.update(k=k, seed=seed)
        validate(cfg)
        configs[t2i_model] = cfg
        path = ROOT / 'configs/t2i_models' / f'{t2i_model}.assets.lock.json'
        lock = read_json(path)
        locks[t2i_model] = dict(
            schema_version=1,
            assets={'renderer': lock['assets']['renderer']},
            provenance=dict(source_lock=str(path.relative_to(ROOT)), sha256=file_hash(path)),
        )
    counts = dict(prompts=len(rows), k=k, images_per_t2i_model=len(rows) * k)
    if not execute:
        return dict(counts, execute=False, output=str(out))
    plan = dict(
        schema_version=1,
        kind='curated_iid_matrix',
        **counts,
        input_hash=digest(data),
        rows_sha256=digest(rows),
        configs=configs,
        upstream_complete=data['metadata']['upstream_complete'] is True,
        allow_partial_input=allow_partial,
        environment=runtime(),
        seed_contract='sha256-prompt-seed-slot-stream-v1',
        asset_hashes={name: digest(lock) for name, lock in locks.items()},
    )
    out.mkdir(parents=True)
    atomic_json(out / 'input.json', data)
    atomic_json(out / 'prompts.json', rows)
    for t2i_model, lock in locks.items():
        atomic_json(out / t2i_model / 'assets.lock.json', lock)
        for shard in range(SHARDS):
            atomic_json(
                out / t2i_model / f'shard-{shard:02d}/manifest.json',
                manifest_for(plan, rows, t2i_model, shard)[1],
            )
    atomic_json(out / 'plan.json', plan)
    atomic_json(out / 'plan-hash.json', {'sha256': digest(plan)})
    return dict(counts, execute=True, output=str(out), plan_hash=digest(plan))


def checked_plan(out):
    out = Path(out)
    plan = read_json(out / 'plan.json')
    if read_json(out / 'plan-hash.json') != {'sha256': digest(plan)}:
        raise ValueError('Frozen plan changed')
    rows = read_json(out / 'prompts.json')
    if digest(rows) != plan['rows_sha256'] or len(rows) != plan['prompts']:
        raise ValueError('Frozen prompts changed')
    for t2i_model in plan['configs']:
        if (
            digest(read_json(out / t2i_model / 'assets.lock.json'))
            != plan['asset_hashes'][t2i_model]
        ):
            raise ValueError('Asset lock changed')
    return plan, rows


def slot_path(run, ident, index):
    return Path(run) / 'images' / ident / f'{index:04d}'


def inspect(run, rows, manifest):
    """Return the verified committed images of a shard, keyed by (prompt id, index)."""
    cfg = manifest['config']
    root = Path(run) / 'images'
    ids, slots = {r['id'] for r in rows}, {f'{i:04d}' for i in range(cfg['k'])}
    if root.exists() and (root.is_symlink() or any(p.name not in ids for p in root.iterdir())):
        raise ValueError('Foreign or symbolic image directory')
    valid = {}
    for row in rows:
        folder = root / row['id']
        if folder.exists() and any(p.name not in slots for p in folder.iterdir()):
            raise ValueError('Foreign image slot')
        for i in range(cfg['k']):
            slot = slot_path(run, row['id'], i)
            if not slot.exists() and not slot.is_symlink():
                continue
            if slot.is_symlink() or {p.name for p in slot.iterdir()} != {
                'image.png',
                'receipt.json',
            }:
                raise ValueError(f'Incomplete committed image slot: {slot}')
            record = read_json(slot / 'receipt.json')
            expected = dict(
                run_hash=digest(manifest),
                prompt_id=row['id'],
                index=i,
                seed=seed_for(row['id'], cfg['seed'], i),
                render_prompt=row['prompt'],
            )
            if any(record.get(key) != value for key, value in expected.items()):
                raise ValueError(f'Receipt identity mismatch: {slot}')
            if (record['sha256'], record['bytes']) != verify_png(
                slot / 'image.png', cfg['resolution']
            ):
                raise ValueError(f'Image checksum mismatch: {slot}')
            valid[(row['id'], i)] = record
    return valid


def summarize(run, rows, manifest, valid):
    cfg = manifest['config']
    items = []
    for row in rows:
        if all((row['id'], i) in valid for i in range(cfg['k'])):
            images = [
                dict(valid[(row['id'], i)], path=f'images/{row["id"]}/{i:04d}/image.png')
                for i in range(cfg['k'])
            ]
            items.append(dict(row, images=images))
    complete = len(items) == len(rows)
    metadata = dict(
        renderer=cfg['renderer'],
        k=cfg['k'],
        n_prompts=len(rows),
        n_images=len(valid),
        n_complete=len(items),
        complete=complete,
        upstream_complete=manifest['upstream_complete'],
        full_pipeline_complete=complete and manifest['upstream_complete'],
    )
    result = dict(
        schema_version=1, kind='curated_iid_summary', run_hash=digest(manifest), metadata=metadata
    )
    atomic_json(Path(run) / 'summary.json', dict(result, items=items))
    return metadata


def worker(out, t2i_model, shard, max_new_images=None, factory=None):
    """Generate the missing images of one shard on the visible GPU.

    Writes images and receipts under `<out>/<t2i_model>/shard-NN/`, then its `summary.json` and
    `status.json`. Stops after `max_new_images` new images (default: no limit). Returns the
    shard summary's metadata. Raises `ValueError` when the plan, prompts, manifest, runtime or a
    committed image differs from the frozen run.
    """
    plan, rows = checked_plan(out)
    if runtime() != plan['environment']:
        raise ValueError('Package versions differ from the prepared run; use its environment')
    run = Path(out) / t2i_model / f'shard-{shard:02d}'
    selected, manifest = manifest_for(plan, rows, t2i_model, shard)
    if read_json(run / 'manifest.json') != manifest:
        raise ValueError('Shard manifest changed')
    cfg = manifest['config']
    with run_lock(run):
        valid = inspect(run, selected, manifest)
        backend, used = None, 0

        def status(state, **extra):
            atomic_json(
                run / 'status.json',
                dict(
                    state=state,
                    updated=time.time(),
                    pid=os.getpid(),
                    expected_images=len(selected) * cfg['k'],
                    verified_images=len(valid),
                    **extra,
                ),
            )

        status('running')
        try:
            for row in selected:
                for i in range(cfg['k']):
                    if (row['id'], i) in valid or used == max_new_images:
                        continue
                    if backend is None:
                        assets = read_json(Path(out) / t2i_model / 'assets.lock.json')
                        entry = assets['assets']['renderer']
                        entry['path'] = expand_path(entry['path'])
                        if factory is None:
                            from baselines.backend import Backend as factory
                        backend = factory(assets, cfg, run)
                    seed = seed_for(row['id'], cfg['seed'], i)
                    image, diagnostics = backend.render(row['prompt'], seed)
                    used += 1
                    stage = run / 'staging' / uuid.uuid4().hex
                    record = dict(
                        run_hash=digest(manifest),
                        prompt_id=row['id'],
                        index=i,
                        seed=seed,
                        render_prompt=row['prompt'],
                        diagnostics=diagnostics,
                    )
                    record = write_slot(stage, image, record, cfg['resolution'])
                    dest = slot_path(run, row['id'], i)
                    dest.parent.mkdir(parents=True, exist_ok=True)
                    os.rename(stage, dest)
                    sync_directory(dest.parent)
                    valid[(row['id'], i)] = record
                    status('running')
            result = summarize(run, selected, manifest, valid)
            status('complete' if result['complete'] else 'budget_exhausted')
            return result
        except BaseException as error:
            summarize(run, selected, manifest, valid)
            status('failed', error=f'{type(error).__name__}: {error}')
            raise
        finally:
            if backend is not None:
                backend.close()


def aggregate(out, t2i_model):
    """Merge the eight complete shard summaries into `<out>/<t2i_model>/summary.json`."""
    plan, rows = checked_plan(out)
    items = []
    for shard in range(SHARDS):
        selected, manifest = manifest_for(plan, rows, t2i_model, shard)
        prefix = f'shard-{shard:02d}'
        path = Path(out) / t2i_model / prefix / 'summary.json'
        result = read_json(path) if path.exists() else dict(run_hash=None)
        if result['run_hash'] != digest(manifest) or not result['metadata']['complete']:
            raise ValueError(f'Incomplete or incompatible shard: {prefix}')
        for row in result['items']:
            images = [dict(image, path=f'{prefix}/{image["path"]}') for image in row['images']]
            items.append(dict(row, images=images))
    items.sort(key=lambda r: r['id'])
    if [r['id'] for r in items] != [r['id'] for r in rows]:
        raise ValueError('Missing or duplicated prompts across shards')
    metadata = dict(
        renderer=t2i_model,
        k=plan['k'],
        n_prompts=len(rows),
        n_complete=len(rows),
        n_images=len(rows) * plan['k'],
        complete=True,
        upstream_complete=plan['upstream_complete'],
        full_pipeline_complete=plan['upstream_complete'],
    )
    atomic_json(
        Path(out) / t2i_model / 'summary.json',
        dict(
            schema_version=1,
            kind='curated_iid_summary',
            plan_hash=digest(plan),
            metadata=metadata,
            items=items,
        ),
    )
    return metadata


def status(out):
    plan, _ = checked_plan(out)
    result = {}
    for t2i_model in sorted(plan['configs']):
        shards = []
        for shard in range(SHARDS):
            path = Path(out) / t2i_model / f'shard-{shard:02d}/status.json'
            shards.append(read_json(path) if path.exists() else dict(state='not_started'))
        result[t2i_model] = dict(
            verified_images=sum(s.get('verified_images', 0) for s in shards),
            expected_images=plan['images_per_t2i_model'],
            shard_states=[s['state'] for s in shards],
            complete=(Path(out) / t2i_model / 'summary.json').exists(),
        )
    return result


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    commands = p.add_subparsers(dest='command', required=True)
    a = commands.add_parser('prepare', help='freeze a new run (read-only without --execute)')
    a.add_argument('--input', type=Path, required=True, help='schema-2 clustered_pool JSON')
    a.add_argument('--out', type=Path, required=True, help='new run directory')
    a.add_argument('--k', type=int, default=4)
    a.add_argument('--seed', type=int, default=42)
    a.add_argument(
        '--allow-partial-input',
        action='store_true',
        help='accept a pool whose curation is not complete; recorded in the plan',
    )
    a.add_argument('--execute', action='store_true')
    for name in ('verify', 'worker', 'aggregate'):
        a = commands.add_parser(name)
        a.add_argument('--out', type=Path, required=True)
        a.add_argument('--t2i-model', choices=sorted(T2I_MODELS), required=True)
        if name == 'worker':
            a.add_argument('--shard', type=int, required=True, choices=range(SHARDS))
            a.add_argument('--max-new-images', type=int, help='stop after this many new images')
    a = commands.add_parser('status')
    a.add_argument('--out', type=Path, required=True)
    args = p.parse_args(argv)
    if args.command == 'prepare':
        result = prepare(
            args.input, args.out, args.k, args.seed, args.allow_partial_input, args.execute
        )
    elif args.command == 'verify':
        # Hash every weight file once per node, before the eight workers load them.
        checked_plan(args.out)
        verify_assets(args.out / args.t2i_model / 'assets.lock.json', ['renderer'])
        result = dict(verified=args.t2i_model)
    elif args.command == 'worker':
        result = worker(args.out, args.t2i_model, args.shard, args.max_new_images)
    elif args.command == 'aggregate':
        result = aggregate(args.out, args.t2i_model)
    else:
        result = status(args.out)
    print(json.dumps(result, indent=2))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
